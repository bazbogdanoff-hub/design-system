/**
 * build/tokens.css + build/typography.css  ->  src/styles.css
 *
 * One import for consumers:  import '@bazbogdanoff/design-system/styles.css'
 * Run as part of `npm run tokens`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
const ROOT = process.cwd();
const out =
  `/* Generated by scripts/bundle-styles.mjs — do not edit. Run \`npm run tokens\`. */\n\n` +
  readFileSync(`${ROOT}/build/tokens.css`, 'utf8') +
  '\n' +
  readFileSync(`${ROOT}/build/typography.css`, 'utf8');
writeFileSync(`${ROOT}/src/styles.css`, out);
console.log(`src/styles.css — ${out.length} bytes`);
